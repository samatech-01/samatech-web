import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
import { createServer } from 'vite';
import { products } from '../src/data/products.js';
import { getScreenshots, getTechnicalInfo, getLicensePrice } from '../src/data/productPresentation.js';

const dom = new JSDOM('<!doctype html><html><body><div id="test-root"></div></body></html>', { url: 'https://samatech.sbs/#/produk/stpos', pretendToBeVisual: true });
const reducedMotion = process.argv.includes('--reduced-motion');
for (const key of ['window', 'document', 'HTMLElement', 'HTMLDialogElement', 'Element', 'Node', 'Event', 'MouseEvent', 'KeyboardEvent', 'MutationObserver', 'getComputedStyle']) globalThis[key] = key === 'getComputedStyle' ? dom.window.getComputedStyle.bind(dom.window) : dom.window[key];
globalThis.IS_REACT_ACT_ENVIRONMENT = true;
window.matchMedia = () => ({ matches: reducedMotion, addListener() {}, removeListener() {}, addEventListener() {}, removeEventListener() {} });
HTMLDialogElement.prototype.showModal = function () { this.setAttribute('open', ''); this.querySelector('[autofocus],button')?.focus(); };
HTMLDialogElement.prototype.close = function () { this.removeAttribute('open'); };
const { default: React, act } = await import('react');
const { createRoot } = await import('react-dom/client');
const server = await createServer({ server: { middlewareMode: true }, appType: 'custom', optimizeDeps: { noDiscovery: true, include: [] } });
const root = createRoot(document.getElementById('test-root'));
const click = async element => { assert.ok(element); await act(async () => element.click()); };
try {
  const { default: Gallery } = await server.ssrLoadModule('/src/components/ScreenshotGallery.jsx');
  const screenshots = [0, 1, 2].map(index => ({ src: `/images/test-${index}.svg`, alt: `Capture ${index + 1}`, width: 1080, height: 1920 }));
  await act(async () => root.render(React.createElement(Gallery, { screenshots, name: 'Test App' })));
  const rail = document.querySelector('.screenshot-track');
  Object.defineProperties(rail, { clientWidth: { value: 300 }, scrollWidth: { value: 900 } });
  [...rail.children].forEach((slide, index) => Object.defineProperty(slide, 'offsetLeft', { value: index * 300 }));
  rail.scrollTo = ({ left, behavior }) => { assert.equal(behavior, reducedMotion ? 'instant' : 'smooth'); rail.scrollLeft = left; rail.dispatchEvent(new Event('scroll')); };
  assert.ok(document.querySelector('[aria-label="Geser screenshot sebelumnya"]').disabled);
  await click(document.querySelector('[aria-label="Geser screenshot berikutnya"]'));
  assert.equal(rail.scrollLeft, 300);
  await click(document.querySelector('[aria-label="Geser screenshot berikutnya"]'));
  assert.ok(document.querySelector('[aria-label="Geser screenshot berikutnya"]').disabled);
  assert.equal(document.querySelectorAll('.gallery-dot').length, 3);
  assert.equal(document.querySelector('.gallery-dot[aria-current="true"]').getAttribute('aria-label'), 'Screenshot 3');
  await click(document.querySelector('.gallery-dot[aria-label="Screenshot 1"]'));
  assert.equal(rail.scrollLeft, 0);
  assert.equal(document.querySelector('.gallery-dot[aria-current="true"]').getAttribute('aria-label'), 'Screenshot 1');
  // A native touch/trackpad scroll emits the same event; gesture physics need a browser.
  await act(async () => { rail.scrollLeft = 0; rail.dispatchEvent(new Event('scroll')); });
  assert.ok(document.querySelector('[aria-label="Geser screenshot sebelumnya"]').disabled);
  const trigger = rail.children[1];
  trigger.focus();
  await click(trigger);
  let dialog = document.querySelector('dialog');
  assert.ok(dialog.open && dialog.getAttribute('aria-labelledby'));
  assert.equal(document.body.style.overflow, 'hidden');
  assert.match(dialog.querySelector('img').alt, /Capture 2/);
  await act(async () => dialog.dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowRight', bubbles: true })));
  assert.equal(dialog.querySelector('img').alt, 'Capture 3');
  await click(dialog.querySelector('[aria-label="Screenshot berikutnya"]'));
  assert.equal(dialog.querySelector('img').alt, 'Capture 1');
  // Browsers emit cancel on Escape; exercise the React cancellation handler.
  await act(async () => dialog.dispatchEvent(new Event('cancel', { cancelable: true })));
  assert.equal(document.querySelector('dialog'), null);
  assert.equal(document.activeElement, trigger);
  assert.equal(document.body.style.overflow, '');
  await click(trigger);
  await click(document.querySelector('[aria-label="Tutup screenshot"]'));
  assert.equal(document.querySelector('dialog'), null);
  await act(async () => root.render(React.createElement(Gallery, { screenshots: getScreenshots({ screenshot: '/images/test-placeholder.svg', screenshotIsPlaceholder: true }), name: products[0].name })));
  assert.equal(document.querySelectorAll('.screenshot-slide').length, 1);
  assert.equal(document.querySelector('.gallery-controls'), null);
  await click(document.querySelector('.screenshot-slide'));
  assert.match(document.querySelector('dialog').textContent, /Placeholder/);
  await click(document.querySelector('[aria-label="Tutup screenshot"]'));
  await act(async () => root.render(React.createElement(Gallery, { screenshots: [], name: 'Empty' })));
  assert.match(document.querySelector('.gallery-empty').textContent, /belum tersedia/);
  assert.deepEqual(getTechnicalInfo(products[0]).filter(([label]) => ['Versi', 'Ukuran APK', 'Diperbarui'].includes(label)), [['Versi', '0.35.5']]);
  assert.deepEqual(getTechnicalInfo(products[1]).filter(([label]) => ['Versi', 'Ukuran APK', 'Diperbarui'].includes(label)), [['Versi', '1.0.0']]);
  assert.equal(getLicensePrice(products[0]), 'Rp300.000');
  assert.equal(products[0].paymentType, 'Sekali bayar');
  assert.equal(products[0].licenseScope, '1 perangkat Android per pembelian');
  assert.equal(getLicensePrice({ price: 'Harga lama' }), 'Harga lama');
  assert.equal(getLicensePrice({ price: 'Harga lama', licensePrice: 'Harga resmi baru' }), 'Harga resmi baru');
  console.log('Detail UI: carousel navigation/end state, scroll sync, reduced-motion, lightbox arrows/close/cancel, focus restoration, body scroll unlock, empty/placeholder gallery and optional facts passed.');
  console.log('Limit: jsdom uses mocked layout and dialog APIs; native swipe, focus trapping, viewport overflow and visual rendering require browser QA.');
} finally {
  await act(async () => root.unmount());
  await server.close();
  dom.window.close();
}
